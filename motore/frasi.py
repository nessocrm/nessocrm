def imposta_lingua(value: str | None) -> str:
    lingua = str(value or "it").strip().lower()
    if lingua not in LINGUE:
        lingua = "it"
    _LINGUA.set(lingua)
    return lingua


def lingua_corrente() -> str:
    return _LINGUA.get()


def _compila(modello: str, parti: dict) -> str:
    testo = modello
    for nome, valore in parti.items():
        testo = testo.replace("{" + nome + "}", str(valore))
    return testo


def traduci(testo: str, lingua: str = "it", **parti) -> str:
    lingua = lingua if lingua in LINGUE else "it"
    if parti:
        modello = testo if lingua == "it" else EN.get(testo, testo)
        return _compila(modello, parti)
    if lingua == "it" or not testo:
        return testo
    if testo in EN:
        return EN[testo]
    for pattern, modello in _MODELLI:
        found = pattern.match(testo)
        if not found:
            continue
        out = modello
        for nome, valore in zip(("a", "b", "c"), found.groups()):
            out = out.replace("{" + nome + "}", valore)
        return out
    return testo


def catalogo() -> dict:
    return {"lingue": list(LINGUE), "en": EN}
